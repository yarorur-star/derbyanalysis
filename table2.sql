SELECT g.NAME_EN AS GROUP_NAME, x.COMMODITY_NAME,
       CAST(x.Y2020 AS DECIMAL(18,0)) AS Y2020,
       CAST(x.Y2021 AS DECIMAL(18,0)) AS Y2021,
       CAST(x.Y2022 AS DECIMAL(18,0)) AS Y2022,
       CAST(x.Y2023 AS DECIMAL(18,0)) AS Y2023,
       CAST(x.Y2024 AS DECIMAL(18,0)) AS Y2024
FROM (
    SELECT g.ID AS GID, g.CODE AS GCODE, c.FAO_CODE, c.NAME_EN AS COMMODITY_NAME,
           SUM(COALESCE(t.VALUE_Y2020,0)) AS Y2020,
           SUM(COALESCE(t.VALUE_Y2021,0)) AS Y2021,
           SUM(COALESCE(t.VALUE_Y2022,0)) AS Y2022,
           SUM(COALESCE(t.VALUE_Y2023,0)) AS Y2023,
           SUM(COALESCE(t.VALUE_Y2024,0)) AS Y2024
    FROM FISHSTAT.REL_COMMODITY_MAJOR r
    JOIN FISHSTAT.REF_COMMODITY_MAJOR2 g ON g.ID = r.PARENT_ID
    JOIN FISHSTAT.REF_COMMODITY c ON c.ID = r.CHILD_ID
    LEFT JOIN FISHSTAT.TSD_TRADE_PP_QUANTITY t ON t.COMMODITY = c.FAO_CODE
    GROUP BY g.ID, g.CODE, c.FAO_CODE, c.NAME_EN
) x
JOIN FISHSTAT.REF_COMMODITY_MAJOR2 g ON g.ID = x.GID
ORDER BY CASE WHEN x.GCODE BETWEEN '0' AND '9' THEN CAST(x.GCODE AS INTEGER) ELSE 99 END,
         x.Y2024 DESC
