-- Таблица 10 (Apache Derby): Группа 7 — "Fishmeals"
-- Колонка 1: сначала товар, затем отступом '     - ' страны-производители этого товара;
-- колонки 2-6: производство за 2020, 2021, 2022, 2023, 2024 (тонны).
SELECT * FROM (
  SELECT x.COMMODITY_NAME AS ITEM,
         CAST(x.Y2020 AS DECIMAL(18,0)) AS Y2020,
         CAST(x.Y2021 AS DECIMAL(18,0)) AS Y2021,
         CAST(x.Y2022 AS DECIMAL(18,0)) AS Y2022,
         CAST(x.Y2023 AS DECIMAL(18,0)) AS Y2023,
         CAST(x.Y2024 AS DECIMAL(18,0)) AS Y2024,
         CAST(x.TOT5   AS DECIMAL(18,0)) AS TOT_5Y,
         0 AS LVL,
         x.FAO_CODE AS GRPKEY,
         x.TOT5 AS ORDKEY
  FROM (
    SELECT c.FAO_CODE, c.NAME_EN AS COMMODITY_NAME,
           SUM(COALESCE(t.VALUE_Y2020,0)) AS Y2020,
           SUM(COALESCE(t.VALUE_Y2021,0)) AS Y2021,
           SUM(COALESCE(t.VALUE_Y2022,0)) AS Y2022,
           SUM(COALESCE(t.VALUE_Y2023,0)) AS Y2023,
           SUM(COALESCE(t.VALUE_Y2024,0)) AS Y2024,
           SUM(COALESCE(t.VALUE_Y2020,0)+COALESCE(t.VALUE_Y2021,0)+COALESCE(t.VALUE_Y2022,0)+COALESCE(t.VALUE_Y2023,0)+COALESCE(t.VALUE_Y2024,0)) AS TOT5
    FROM FISHSTAT.REL_COMMODITY_MAJOR r
    JOIN FISHSTAT.REF_COMMODITY_MAJOR2 g ON CAST(g.ID AS VARCHAR(20)) = CAST(r.PARENT_ID AS VARCHAR(20))
    JOIN FISHSTAT.REF_COMMODITY c        ON CAST(c.ID AS VARCHAR(20)) = CAST(r.CHILD_ID AS VARCHAR(20))
    JOIN FISHSTAT.TSD_TRADE_PP_QUANTITY t ON CAST(t.COMMODITY AS VARCHAR(20)) = CAST(c.FAO_CODE AS VARCHAR(20))
    WHERE CAST(g.CODE AS VARCHAR(20)) = '7'
    GROUP BY c.FAO_CODE, c.NAME_EN
    HAVING SUM(COALESCE(t.VALUE_Y2020,0)+COALESCE(t.VALUE_Y2021,0)+COALESCE(t.VALUE_Y2022,0)+COALESCE(t.VALUE_Y2023,0)+COALESCE(t.VALUE_Y2024,0)) > 0
  ) x
  UNION ALL
  SELECT '     - ' || CAST(cn.NAME_EN AS VARCHAR(80)) AS ITEM,
         CAST(SUM(COALESCE(t.VALUE_Y2020,0)) AS DECIMAL(18,0)) AS Y2020,
         CAST(SUM(COALESCE(t.VALUE_Y2021,0)) AS DECIMAL(18,0)) AS Y2021,
         CAST(SUM(COALESCE(t.VALUE_Y2022,0)) AS DECIMAL(18,0)) AS Y2022,
         CAST(SUM(COALESCE(t.VALUE_Y2023,0)) AS DECIMAL(18,0)) AS Y2023,
         CAST(SUM(COALESCE(t.VALUE_Y2024,0)) AS DECIMAL(18,0)) AS Y2024,
         CAST(SUM(COALESCE(t.VALUE_Y2020,0)+COALESCE(t.VALUE_Y2021,0)+COALESCE(t.VALUE_Y2022,0)+COALESCE(t.VALUE_Y2023,0)+COALESCE(t.VALUE_Y2024,0)) AS DECIMAL(18,0)) AS TOT_5Y,
         1 AS LVL,
         c.FAO_CODE AS GRPKEY,
         0 AS ORDKEY
  FROM FISHSTAT.TSD_TRADE_PP_QUANTITY t
  JOIN FISHSTAT.REF_COUNTRY cn          ON CAST(cn.UN_CODE AS VARCHAR(3)) = CAST(t.COUNTRY AS VARCHAR(3))
  JOIN FISHSTAT.REF_COMMODITY c         ON CAST(c.FAO_CODE AS VARCHAR(20)) = CAST(t.COMMODITY AS VARCHAR(20))
  JOIN FISHSTAT.REL_COMMODITY_MAJOR r   ON CAST(r.CHILD_ID AS VARCHAR(20)) = CAST(c.ID AS VARCHAR(20))
  JOIN FISHSTAT.REF_COMMODITY_MAJOR2 g  ON CAST(g.ID AS VARCHAR(20)) = CAST(r.PARENT_ID AS VARCHAR(20))
  WHERE CAST(g.CODE AS VARCHAR(20)) = '7'
  GROUP BY cn.NAME_EN, t.COUNTRY, c.FAO_CODE, c.NAME_EN
  HAVING SUM(COALESCE(t.VALUE_Y2020,0)+COALESCE(t.VALUE_Y2021,0)+COALESCE(t.VALUE_Y2022,0)+COALESCE(t.VALUE_Y2023,0)+COALESCE(t.VALUE_Y2024,0)) > 0
) y
ORDER BY CASE WHEN LVL = 0 THEN ORDKEY ELSE -ORDKEY END DESC,
         GRPKEY,
         LVL,
         TOT_5Y DESC
