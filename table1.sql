SELECT CAST(c.NAME_EN AS VARCHAR(80)) AS COUNTRY,
       CAST(SUM(COALESCE(t.VALUE_Y2020,0)) AS DECIMAL(18,0)) AS Y2020,
       CAST(SUM(COALESCE(t.VALUE_Y2021,0)) AS DECIMAL(18,0)) AS Y2021,
       CAST(SUM(COALESCE(t.VALUE_Y2022,0)) AS DECIMAL(18,0)) AS Y2022,
       CAST(SUM(COALESCE(t.VALUE_Y2023,0)) AS DECIMAL(18,0)) AS Y2023,
       CAST(SUM(COALESCE(t.VALUE_Y2024,0)) AS DECIMAL(18,0)) AS Y2024
FROM FISHSTAT.TSD_TRADE_PP_QUANTITY t
JOIN FISHSTAT.REF_COUNTRY c ON c.UN_CODE = t.COUNTRY
GROUP BY c.NAME_EN
ORDER BY SUM(COALESCE(t.VALUE_Y2020,0)+COALESCE(t.VALUE_Y2021,0)+COALESCE(t.VALUE_Y2022,0)+COALESCE(t.VALUE_Y2023,0)+COALESCE(t.VALUE_Y2024,0)) DESC
FETCH NEXT 10 ROWS ONLY
